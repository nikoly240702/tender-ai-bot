#!/bin/bash
# Регулярная догрузка данных ЕИС для аналитики ниш.
#
# Ставится на сервер как /opt/tender/eis-ingest.sh и запускается
# systemd-таймером tender-eis-ingest.timer (ежедневно 02:20 UTC).
# Копия лежит здесь, чтобы скрипт не существовал только на сервере.
#
# ВАЖНО: контейнер берёт код из ОБРАЗА, а не из работающего воркера.
# Правка, проверенная через `docker compose cp` в живой контейнер,
# сюда не попадает — нужен деплой. Таймер держать выключенным, пока
# изменения разбора не выкачены: иначе он будет писать данные старым
# кодом каждую ночь.
#
# Запускается отдельным контейнером, а НЕ внутри работающего воркера:
# загрузка упирается в CPU на разборе XML и отняла бы его у бота. По
# той же причине в проекте матчинг вынесен в отдельный сервис.
#
# Окно в несколько суток, а не ровно вчера: документ может появиться в
# архиве позже своей даты, а повтор ничего не стоит — журнал загрузки
# сверяет sha256 архива и уже загруженное пропускает.
set -uo pipefail
cd /opt/tender

REGIONS="${EIS_INGEST_REGIONS:-ЦФО}"
DAYS_BACK="${EIS_INGEST_DAYS_BACK:-3}"
FROM=$(date -u -d "${DAYS_BACK} days ago" +%F)
TO=$(date -u +%F)

echo "=== $(date -u +'%F %T') догрузка ЕИС: регионы ${REGIONS}, ${FROM}..${TO}"
# --entrypoint python обязателен: штатный entrypoint образа смотрит на
# SERVICE_ROLE и поднимает бота, а переданную команду игнорирует. Без
# этого запускается ВТОРОЙ экземпляр бота рядом с рабочим.
docker compose run --rm --no-deps -T --entrypoint python worker \
    -m tender_sniper.niche.ingest \
    --region "${REGIONS}" --from "${FROM}" --to "${TO}"
code=$?
echo "=== $(date -u +'%F %T') завершено, код ${code}"
exit $code
