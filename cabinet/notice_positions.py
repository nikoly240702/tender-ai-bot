"""Позиции для закупщика из извещения ЕИС.

Зачем: до этого закупщик получал позиции из `ai_analysis.items_description`,
а разбор документации почти никогда не запускался (на 21.09.2026 — 362
карточки и 0 анализов). На деле он всегда искал по названию тендера, то
есть по товарной КАТЕГОРИИ.

Замер 21.09.2026 на завершённой закупке 0373100128326000093
(светильники 595х595, 50 шт, победитель 4 190 ₽/шт):

  по названию «светильник светодиодный внутреннего освещения»
      449 / 739 / 1 990 / 7 483 ₽ — четыре разных товара, ни одного нужного
  по описанию без чисел
      290 ₽ (декоративный) / 15 600 ₽ / 1 054 ₽ — снова мимо
  по описанию с числами из извещения («40 Вт», «595 мм»)
      1 179 ₽ и 1 344 ₽ — оба тот самый светильник

Разницу делают именно числа, поэтому они обязаны доезжать до позиции.
"""
import logging
from typing import List, Optional

from tender_sniper.sources import eis_integration as eis

logger = logging.getLogger(__name__)

# Сколько характеристик кладём в позицию. Потолок нужен с двух сторон:
# у ноутбука их 38, и целиком они и запрос размывают, и раздувают список
# требований, по которому потом сверяются страницы (а от длины этого
# списка напрямую зависит потолок ответа модели, см. offer_reader).
MAX_CHARACTERISTICS = 10

# Длина позиции. Столько же берёт offer_reader под требования.
MAX_POSITION_LEN = 300


def _is_absence(value: str) -> bool:
    """«Нет» как значение — требование об ОТСУТСТВии свойства.

    Для подбора оно бесполезно вдвойне: искать по нему нечего, а
    подтвердить со страницы поставщика нельзя — каталог не пишет, чего
    в товаре нет. В требованиях такие строки дают только «не
    подтверждено». Пример из закупки 0173300004226000004: «Наличие
    стилуса в комплекте: Нет», «Использование eSIM-карты: Нет».
    """
    return value.strip().lower() in ('нет', 'отсутствует', 'не требуется')


def _is_affirmative(value: str) -> bool:
    """Значение вида «Да» — требование о наличии свойства.

    Смысл ему придаёт только название характеристики, поэтому в
    поисковую часть позиции оно не годится.
    """
    return value.strip().lower() in ('да', 'наличие', 'требуется', 'есть')


def _rank(char: eis.Characteristic):
    """Насколько характеристика задаёт товар. Меньше — важнее.

    Первым идёт порядок, вторым — узость требования. Порядок такой:

    0. Число, которым товар назван в каталоге: достижимая верхняя
       граница с единицей. Чем уже вилка, тем конкретнее требование —
       у светильника из закупки 0373100128326000093 мощность 35–40 Вт
       это 12% разброса, световой поток 3000–4000 лм — 25%. По
       мощности его и ищут в магазине.
    2. Текстовое значение — «Поликарбонат», «DDR4», «SSD». Чисел не
       даёт, но товар сужает.
    3. Вилка с недостижимой верхней границей — «менее 600 мм». Товар
       здесь 595 мм, и ни одного из двух чисел в его названии нет.
    4. Односторонний порог — «не менее 16 Гбайт» — и число без
       единицы. Выполняет и любая модель лучше, поиск не сужает.

    Порядок внутри группы сохраняется исходный: в извещении
    характеристики идут по алфавиту, и содержательного смысла в этом
    нет — угадывать тут нечего.
    """
    if not char.is_numeric:
        return (2, 0.0)
    if _has_nominal(char):
        return (0, char.span)
    if char.span is not None:
        return (3, char.span)
    return (4, 0.0)


def _value_text(char: eis.Characteristic) -> str:
    """Значение характеристики для поиска.

    Двусторонняя вилка сворачивается до верхней границы: «более 35 и не
    более 40 Вт» → «до 40 Вт». Причина в замере 21.09.2026 — вилка даёт
    в запрос ДВА числа, и получалось «мощность 35 40 вт 500», чего не
    пишет ни один магазин; выдача схлопывалась до нуля предложений. С
    одним числом запрос становится «мощность до 40 вт» — так товар и
    называют.

    Теряется нижняя граница, то есть требование становится мягче. Это
    безопасная сторона: страница поставщика и так редко подтверждает
    всё, и лишние отказы стоят дороже лишних кандидатов.
    """
    if _has_nominal(char):
        high = int(char.high) if float(char.high).is_integer() else char.high
        return f'до {high} {_unit_text(char.unit)}'
    return char.text


def _unit_text(unit: str) -> str:
    """Одно обозначение единицы, а не весь список из ОКЕИ.

    Классификатор отдаёт альтернативные написания через «;»: у литра
    это «л; дм[3*]». В запрос и в требование должно уходить первое —
    «бойлер до 1100 л», а не «до 1100 л; дм[3*]».
    """
    return (unit or '').split(';')[0].strip()


def _has_nominal(char: eis.Characteristic) -> bool:
    """Есть ли у требования число, которым товар назван в каталоге.

    Только у достижимой верхней границы. «Не более 40 Вт» — это
    светильник ровно на 40 Вт, так его и продают. «Менее 600 мм» — это
    595 мм, и числа 600 в названии нет ни у кого: замер 21.09.2026
    показал, что запрос с «600 мм» не находит ничего, тогда как с
    «40 Вт» находит нужный светильник.
    """
    return (char.span is not None and char.high is not None
            and char.unit is not None and char.high_inclusive)


# Сколько значений уходит в «голову» позиции — ту часть, из которой
# строится поисковый запрос. Три: запрос ограничен 12 словами вместе со
# словами намерения, и больше туда всё равно не влезет.
HEAD_VALUES = 3


def render_position(obj: eis.PurchaseObject) -> str:
    """Позиция одной строкой: сначала для поиска, потом для сверки.

    Порядок не косметический. Поисковый запрос строится из начала
    строки, а сверка требований читает её целиком, и нужны им разные
    слова. Каталог пишет «светильник 40 Вт поликарбонат», а не
    «мощность до 40 Вт, материал рассеивателя Поликарбонат»: названия
    характеристик — это ярлыки полей, в запросе они занимают место и
    ничего не находят. Ровно это уже отмечено в eis_integration про
    описание тендера, только там ярлыки убирались совсем, а здесь они
    нужны дальше по строке — иначе требование «40 Вт» непонятно чего.
    """
    usable = [c for c in obj.characteristics if not _is_absence(c.text)]
    usable.sort(key=_rank)
    chosen = usable[:MAX_CHARACTERISTICS]

    head = obj.name
    for char in chosen:
        if len(head.split()) - len(obj.name.split()) >= HEAD_VALUES:
            break
        value = _value_text(char)
        # «Да» в голове — пустой звук: без своего ярлыка оно не говорит
        # ничего, и в запрос уходило буквально «ноутбук pcie да».
        # В хвосте, рядом с «наличие сканера отпечатка», оно осмысленно.
        if _is_affirmative(value):
            continue
        head += ' ' + value

    text = head
    for char in chosen:
        candidate = f'{text}, {char.name.lower()} {_value_text(char)}'
        if len(candidate) > MAX_POSITION_LEN:
            break
        text = candidate
    return text


def positions_from_notice(xml_bytes: bytes) -> List[str]:
    return [render_position(o) for o in eis.parse_purchase_objects(xml_bytes)
            if o.name]


def fetch_positions(tender_number: str) -> Optional[List[str]]:
    """Позиции закупки из её извещения. None, если достать не удалось.

    Работает синхронно (клиент ЕИС на requests) — вызывать через поток.
    None и пустой список различаются намеренно: None значит «не
    дозвонились, можно попробовать позже», пустой список — «извещение
    прочитано, позиций в нём нет», и повторять запрос незачем.
    """
    client = eis.EisIntegrationClient()
    if not client.token:
        logger.info('Позиции из извещения: не задан %s', eis.TOKEN_ENV_VAR)
        return None
    try:
        urls = client.request_archives_by_number(
            eis.SUBSYSTEM_NOTICES, tender_number)
    except Exception as exc:  # noqa: BLE001
        logger.warning('Позиции из извещения %s: %s', tender_number, str(exc)[:120])
        return None

    for url in urls:
        try:
            archive = client.download(url)
        except Exception as exc:  # noqa: BLE001
            logger.warning('Архив извещения %s: %s', tender_number, str(exc)[:120])
            continue
        for doc_type, xml in eis.iter_documents(archive):
            # В архиве процедуры лежат и протоколы, и изменения. Позиции
            # с характеристиками есть только в самом извещении.
            if not doc_type.startswith('epNotification'):
                continue
            try:
                positions = positions_from_notice(xml)
            except Exception as exc:  # noqa: BLE001
                logger.warning('Разбор извещения %s: %s',
                               tender_number, str(exc)[:120])
                continue
            if positions:
                return positions
    return None
