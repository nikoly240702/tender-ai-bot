"""Человеческие тексты для ошибок на странице входа.

Раньше telegram_auth_callback отдавал ошибки как `web.Response(text=...)` —
голый текст без вёрстки, и в одной из веток ссылался на несуществующего
бота @TenderSniperBot (реальный — @TenderAI111_bot). Для случайного
посетителя кабинета это выглядело как сломанный сайт.

Коды ошибок везут только как `?error=` в редиректе на /cabinet/login —
сама страница логина решает, как их показать, здесь только тексты.
"""
from typing import Dict, Optional

# Имя реального бота. BOT_USERNAME как переменная окружения здесь не
# читается специально: в проде её никто не задавал, и три места в коде
# (реферальные ссылки, возврат после оплаты YooKassa, эта страница) тихо
# откатывались на зашитый дефолт TenderSniperBot — бота с таким именем
# не существует.
BOT_USERNAME = 'TenderAI111_bot'
BOT_LINK = f'https://t.me/{BOT_USERNAME}'

_DEFAULT = {
    'title': 'Не получилось войти',
    'message': 'Попробуйте снова через несколько секунд. Если не поможет — '
               f'напишите в бота @{BOT_USERNAME}, опишем проблему и поможем войти.',
    'bot_link': BOT_LINK,
}

_ERRORS: Dict[str, dict] = {
    'bot_not_configured': {
        'title': 'Кабинет временно недоступен',
        'message': 'Вход через Telegram сейчас не настроен на сервере. '
                   'Это наша ошибка, а не ваша — уже знаем и чиним.',
        'bot_link': None,
    },
    'missing_params': {
        'title': 'Не получилось войти',
        'message': 'Telegram не передал данные для входа. Чаще всего это '
                   'блокировщик рекламы или скриптов — попробуйте выключить '
                   'его для этой страницы и войти снова.',
        'bot_link': None,
    },
    'invalid_auth': {
        'title': 'Ссылка для входа устарела',
        'message': 'Подпись входа не прошла проверку или успела протухнуть. '
                   'Обновите страницу и попробуйте войти через Telegram ещё раз.',
        'bot_link': None,
    },
    'user_not_found': {
        'title': 'Сначала нужно запустить бота',
        'message': f'Кабинет не нашёл вас среди пользователей бота. Откройте '
                   f'@{BOT_USERNAME} в Telegram, нажмите «Старт» и возвращайтесь '
                   'на эту страницу — вход сработает сразу.',
        'bot_link': BOT_LINK,
    },
}


def resolve_login_error(code: Optional[str]) -> Optional[dict]:
    """Текст для баннера на странице логина по коду ошибки.

    Незнакомый код (например, подделанный в URL) не должен ронять
    страницу — отдаём обобщённый, но осмысленный текст вместо падения.
    """
    if not code:
        return None
    return _ERRORS.get(code, _DEFAULT)
